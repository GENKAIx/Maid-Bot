// Показ (ниже метки «показ»): опечатка и «переспросит» — вперёд, до обрезки до четырёх; что перенеслось за разрешённые ряды
// (box.dataset.rows, по умолчанию 2) — убрано из DOM. Раскладка — как flex-wrap: ширина метки по длине текста, зазор 5px, ряд 29px.
function fakeBox(width, rows) {
  const classes = new Set(["hidden"]);
  const box = { dataset: rows ? { rows: String(rows) } : {}, children: [], renders: 0 };
  box.classList = { toggle: (c, on) => (on ? classes.add(c) : classes.delete(c)), contains: (c) => classes.has(c) };
  box.replaceChildren = (...els) => { box.renders++; box.children = els; for (const el of els) el.parent = box; };
  box.getClientRects = () => (classes.has("hidden") ? [] : [{}]);
  box.rowOf = (el) => {
    let x = 0, row = 0;
    for (const c of box.children) {
      const w = c.textContent.length * 7 + 20;
      if (x && x + w > width) { row++; x = 0; }
      if (c === el) return row;
      x += w + 5;
    }
    return -1;
  };
  return box;
}
const showCtx = { document: { createElement: () => {
  const el = { className: "", textContent: "", title: "" };
  el.getBoundingClientRect = () => ({ top: 100 + el.parent.rowOf(el) * 29 });
  el.remove = () => { el.parent.children = el.parent.children.filter((c) => c !== el); };
  return el;
} } };
