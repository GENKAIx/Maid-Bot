const LINES_KEY = "maid.lines";
let linesRecent = {};
try { linesRecent = JSON.parse(localStorage.getItem(LINES_KEY) ?? "{}") ?? {}; } catch { linesRecent = {}; }

function lineFits(v, hour) {
  if (v.h) {
    const [a, b] = v.h;
    if (a < b ? hour < a || hour >= b : hour < a && hour >= b) return false;
  }
  if (v.day && (typeof dayMood === "undefined" || dayMood !== v.day)) return false;
  return true;
}
// Вариант целиком ({ t, m }) — для тычков, где нужна и эмоция.
function lineItem(key, vars = {}) {
  const all = LINES[key] ?? [];
  const hour = new Date().getHours();
  const fit = all.filter((v) => lineFits(v, hour));
  const pool = fit.length ? fit : all;
  if (!pool.length) return { t: "", m: "neutral" };
  const recent = linesRecent[key] ?? [];
  const keep = Math.min(pool.length - 1, Math.ceil(pool.length * 0.6));
  const fresh = pool.filter((v) => !recent.slice(-keep).includes(v.t));
  const from = fresh.length ? fresh : pool;
  const v = from[Math.floor(Math.random() * from.length)];
  linesRecent[key] = [...recent.filter((t) => t !== v.t), v.t].slice(-Math.max(1, all.length - 1));
  try { localStorage.setItem(LINES_KEY, JSON.stringify(linesRecent)); } catch {}
  return { m: v.m ?? "neutral", t: v.t.replace(/\{(\w+)\}/g, (_, k) => vars[k] ?? "") };
}
function line(key, vars) {
  return lineItem(key, vars).t;
}
