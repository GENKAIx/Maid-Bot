import { AsyncLocalStorage } from "node:async_hooks";
import fs from "node:fs";
import path from "node:path";
import { DatabaseSync } from "node:sqlite";

// Один интерфейс над двумя базами: SQLite (у себя на ПК, файл) и Postgres (Render).
// SQL пишется один: «?» в параметрах, «{pk}» и «{real}» в схеме — драйвер переводит под свою базу.

export type Dialect = "sqlite" | "pg";

export interface Driver {
  readonly dialect: Dialect;
  all<T>(sql: string, args?: unknown[]): Promise<T[]>;
  run(sql: string, args?: unknown[]): Promise<number>;
  /** Несколько команд без параметров (схема). */
  exec(sql: string): Promise<void>;
  /** Всё внутри — одна транзакция; вложенный вызов идёт в ту же. */
  tx<T>(fn: () => Promise<T>): Promise<T>;
  close(): Promise<void>;
}

const SCHEMA_WORDS: Record<Dialect, Record<string, string>> = {
  sqlite: { "{pk}": "INTEGER PRIMARY KEY", "{real}": "REAL" },
  pg: { "{pk}": "INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY", "{real}": "DOUBLE PRECISION" },
};

export function schemaFor(dialect: Dialect, sql: string): string {
  return sql.replace(/\{pk\}|\{real\}/g, (w) => SCHEMA_WORDS[dialect][w]);
}

/** SQLite в одном соединении: пока идёт транзакция, остальные запросы ждут её конца. */
export class SqliteDriver implements Driver {
  readonly dialect = "sqlite" as const;
  private db: DatabaseSync;
  private inTx = new AsyncLocalStorage<true>();
  private lock: Promise<unknown> = Promise.resolve();

  constructor(file: string) {
    if (file !== ":memory:") fs.mkdirSync(path.dirname(file), { recursive: true });
    this.db = new DatabaseSync(file);
    this.db.exec("PRAGMA journal_mode = WAL; PRAGMA foreign_keys = ON;");
  }

  private async ready() {
    if (!this.inTx.getStore()) await this.lock;
  }
  async all<T>(sql: string, args: unknown[] = []): Promise<T[]> {
    await this.ready();
    return this.db.prepare(sql).all(...(args as never[])) as T[];
  }
  async run(sql: string, args: unknown[] = []): Promise<number> {
    await this.ready();
    return Number(this.db.prepare(sql).run(...(args as never[])).changes);
  }
  async exec(sql: string) {
    await this.ready();
    this.db.exec(sql);
  }
  tx<T>(fn: () => Promise<T>): Promise<T> {
    if (this.inTx.getStore()) return fn();
    const go = async () => {
      this.db.exec("BEGIN");
      try {
        const r = await this.inTx.run(true, fn);
        this.db.exec("COMMIT");
        return r;
      } catch (e) {
        this.db.exec("ROLLBACK");
        throw e;
      }
    };
    const p = this.lock.then(go, go);
    this.lock = p.catch(() => {});
    return p;
  }
  async close() {
    await this.lock;
    this.db.close();
  }
}

/** Что нужно от Postgres-клиента: так подходят и пул `pg`, и PGlite в тестах. */
export interface PgClient {
  query(sql: string, params?: unknown[]): Promise<{ rows: unknown[]; rowCount?: number | null; affectedRows?: number }>;
  /** Несколько команд разом (у PGlite); у пула `pg` это делает query без параметров. */
  exec?(sql: string): Promise<unknown>;
}

const placeholders = new Map<string, string>();
function toPg(sql: string): string {
  let out = placeholders.get(sql);
  if (out === undefined) {
    let n = 0;
    out = sql.replace(/\?/g, () => `$${++n}`);
    placeholders.set(sql, out);
  }
  return out;
}

export class PgDriver implements Driver {
  readonly dialect = "pg" as const;
  private client = new AsyncLocalStorage<PgClient>();

  constructor(
    private base: PgClient,
    private begin: <T>(fn: (c: PgClient) => Promise<T>) => Promise<T>,
    private end: () => Promise<void> = async () => {},
  ) {}

  private c(): PgClient {
    return this.client.getStore() ?? this.base;
  }
  async all<T>(sql: string, args: unknown[] = []): Promise<T[]> {
    return (await this.c().query(toPg(sql), args)).rows as T[];
  }
  async run(sql: string, args: unknown[] = []): Promise<number> {
    const r = await this.c().query(toPg(sql), args);
    return r.rowCount ?? r.affectedRows ?? 0;
  }
  async exec(sql: string) {
    const c = this.c();
    if (c.exec) await c.exec(sql);
    else await c.query(sql);
  }
  tx<T>(fn: () => Promise<T>): Promise<T> {
    if (this.client.getStore()) return fn();
    return this.begin((c) => this.client.run(c, fn));
  }
  close() {
    return this.end();
  }
}

/** Postgres по адресу DATABASE_URL (Render). */
export async function openPostgres(url: string): Promise<PgDriver> {
  const pg = (await import("pg")).default;
  // COUNT и BIGINT — числами, не строками.
  pg.types.setTypeParser(20, (v: string) => Number(v));
  pg.types.setTypeParser(1700, (v: string) => Number(v));
  const local = /localhost|127\.0\.0\.1/.test(url);
  const pool = new pg.Pool({ connectionString: url, max: 5, ssl: local ? undefined : { rejectUnauthorized: false } });
  return new PgDriver(
    pool,
    async (fn) => {
      const c = await pool.connect();
      try {
        await c.query("BEGIN");
        const r = await fn(c);
        await c.query("COMMIT");
        return r;
      } catch (e) {
        await c.query("ROLLBACK").catch(() => {});
        throw e;
      } finally {
        c.release();
      }
    },
    () => pool.end(),
  );
}
