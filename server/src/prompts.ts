const byId = new Map(PROMPTS.map((s) => [s.id, s]));
export const promptSpec = (id: string): PromptSpec | undefined => byId.get(id);

/** Подставить значения vars вместо {{имя}} за один проход; незнакомое {{имя}} остаётся как есть. */
export function fill(body: string, vars: Readonly<Record<string, string>> = {}): string {
  return body.replace(/\{\{([a-z][a-z0-9_]*)\}\}/g, (w, name: string) => (Object.hasOwn(vars, name) ? vars[name] : w));
}

/** Проверка текста версии; ошибка — строкой, всё хорошо — null. Копия — promptError в web/src/admin.ts (тест сверяет). */
export function checkPrompt(spec: PromptSpec, body: unknown): string | null {
  if (typeof body !== "string" || !body.trim()) return "текст пустой";
  if (body.length > spec.max) return `текст длиннее ${spec.max} знаков`;
  // eslint-disable-next-line no-control-regex
  if (/[\u0000-\u0008\u000b-\u001f\u007f]/.test(body)) return "в тексте служебные знаки (можно только перенос строки и табуляцию)";
  for (const m of body.matchAll(/\{\{([^{}]*)\}\}/g)) {
    if (!spec.vars.includes(m[1])) return `незнакомая подстановка {{${m[1]}}}` + (spec.vars.length ? ` (можно: ${spec.vars.map((v) => `{{${v}}}`).join(", ")})` : " (здесь подстановок нет)");
  }
  for (const r of spec.required) if (!body.includes(`{{${r}}}`)) return `нужна подстановка {{${r}}}`;
  const apart = spec.apart ?? [];
  for (const par of body.split("\n\n")) {
    const both = apart.filter((a) => par.includes(`{{${a}}}`));
    if (both.length > 1) return `${both.map((a) => `{{${a}}}`).join(" и ")} — в разных абзацах (между ними пустая строка)`;
  }
  for (const s of spec.mustContain ?? []) if (!body.includes(s)) return `в тексте должно остаться «${s}»`;
  return null;
}

