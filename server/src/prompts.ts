export interface PromptSpec {
  /** Ключ: латиница, «раздел.часть» (parse.rules, chat.rules); тот же — в адресе /admin/prompts/<id>. */
  id: string;
  section: PromptSection;
  title: string;
  /** Где и зачем используется — подсказка в админке. */
  hint: string;
  /** Подстановки, которые можно использовать в тексте ({{voice}}). */
  vars: readonly string[];
  /** Какие из vars должны остаться в тексте. */
  required: readonly string[];
  /** Что значит каждая подстановка (для админки). */
  varHints?: Readonly<Record<string, string>>;
  /** Самая большая длина текста, знаков. */
  max: number;
  /** Текст «как в коде» — версия 0. */
  def: string;
  /** Что вокруг этого текста строит код (видно в админке только для чтения). */
  readonly?: string;
  /** Подстроки, которые обязаны остаться (без них ломается разбор ответа). */
  mustContain?: readonly string[];
  /** Подстановки, которые должны стоять в разных абзацах (между абзацами — пустая строка): код выбрасывает абзац целиком,
   *  если подставлять нечего (profile.traits), и абзац с двумя такими подстановками пропал бы вместе с обеими. */
  apart?: readonly string[];
  /** Пример значений подстановок для предпросмотра. */
  sample?: Readonly<Record<string, string>>;
  /** Что код добавляет вокруг текста — для предпросмотра «целиком». */
  frame?: (filled: string) => string;
}

