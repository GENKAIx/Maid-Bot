let live = new Map<string, string>();
let loadedAt = -Infinity;
let started = 0, applied = 0;

/** Действующий текст промпта id с подстановками. Нет своей версии — def. Незнакомый id — ошибка программы. */
export function prompt(id: string, vars?: Readonly<Record<string, string>>): string {
  const spec = byId.get(id);
  if (!spec) throw new Error(`[prompts] нет промпта ${id}`);
  return fill(live.get(id) ?? spec.def, vars);
}

/** Только для тестов: действующие тексты без базы (до следующего loadPrompts); без аргумента — всё «как в коде». */
export function overridePrompts(bodies: Readonly<Record<string, string>> = {}): void {
  live = new Map(Object.entries(bodies).filter(([id]) => byId.has(id)));
}

/** Пример для предпросмотра из модуля-владельца (там доступны части, которые строит код, — без цикла импортов). */
const previews = new Map<string, { sample?: Readonly<Record<string, string>>; frame?: (filled: string) => string }>();
export function setPromptPreview(id: string, p: { sample?: Readonly<Record<string, string>>; frame?: (filled: string) => string }): void {
  previews.set(id, p);
}

/** О негодной версии — одна строка в лог на процесс (а не при каждом чтении). */
const warned = new Set<string>();
/** Действующие версии из базы. good: id → { version, body } — то, что идёт модели. raw: id → строка prompt_active как есть
 *  (номер «было» для журнала и выбора версии). Версия, которую не пропускает нынешняя проверка (в коде поменялись подстановки),
 *  и пропавшая — в good нет (модель получает «как в коде»), в raw остаётся: админка показывает, что записанная версия не подходит. */
async function activeOf(store: Store) {
  const good = new Map<string, { version: number; body: string }>();
  const raw = new Map<string, PromptActiveRow>();
  for (const a of await store.promptActive()) {
    const spec = byId.get(a.prompt_id);
    if (!spec) continue;
    raw.set(a.prompt_id, a);
    if (a.version <= 0) continue;
    const v = await store.promptVersion(a.prompt_id, a.version);
    if (!v || checkPrompt(spec, v.body)) {
      const key = `${a.prompt_id} v${a.version}`;
      if (!warned.has(key)) warned.add(key), console.error("[prompts] версия не годится, взят текст из кода:", key);
      continue;
    }
    good.set(a.prompt_id, { version: a.version, body: v.body });
  }
  return { good, raw };
}

/** Перечитать сейчас; чтение, начатое раньше уже применённого, — мимо (как loadTariffs). */
export async function loadPrompts(store: Store, now = Date.now()): Promise<void> {
  const my = ++started;
  const { good } = await activeOf(store);
  if (my > applied) {
    applied = my;
    live = new Map([...good].map(([id, a]) => [id, a.body]));
    loadedAt = now;
  }
}
/** Перечитать, если с прошлого чтения прошло PROMPT_RELOAD_MS; true — перечитали. */
export async function refreshPrompts(store: Store, now = Date.now()): Promise<boolean> {
  if (now - loadedAt < PROMPT_RELOAD_MS) return false;
  await loadPrompts(store, now);
  return true;
}
/** Перечитывать раз в минуту (index.ts). Возвращает «остановить». */
export function watchPrompts(store: Store, clock: () => number = Date.now): () => void {
  const t = setInterval(() => void refreshPrompts(store, clock()).catch((e) => console.error("[prompts]", (e as Error).message)), PROMPT_RELOAD_MS / 4);
  t.unref?.();
  return () => clearInterval(t);
}

export class PromptError extends Error {
  constructor(readonly status: number, message: string) { super(message); }
}

/** Правки промптов на этом процессе — по одной: следующая начинается, когда прошлая записана и перечитана. */
let saveLock: Promise<unknown> = Promise.resolve();
function locked<T>(fn: () => Promise<T>): Promise<T> {
  const r = saveLock.then(fn, fn);
  saveLock = r.catch(() => {});
  return r;
}

const needReason = (reason: unknown): string => {
  const r = typeof reason === "string" ? reason.trim() : "";
  if (r.length < 3) throw new PromptError(400, "напишите причину (хотя бы 3 знака)");
  if (r.length > 300) throw new PromptError(400, "причина — не длиннее 300 знаков");
  // eslint-disable-next-line no-control-regex
  if (/[\u0000-\u001f\u007f\u202a-\u202e\u2066-\u2069]/.test(r)) throw new PromptError(400, "в причине служебные знаки");
  return r;
};
const fields = (body: unknown) => (body && typeof body === "object" ? body : {}) as Record<string, unknown>;
function specOf(id: unknown): PromptSpec {
  const s = typeof id === "string" ? byId.get(id) : undefined;
  if (!s) throw new PromptError(404, "нет такого промпта");
  return s;
}
/** Самый большой номер версии: столбец INTEGER (int4 в Postgres). */
const MAX_VERSION = 2_147_483_647;

/** «Сохранить как новую версию» (POST /api/admin/prompts/<id>/save { body, reason }): версия n+1 и сразу действует. */
export async function savePrompt(store: Store, by: number, body: unknown, now = new Date()) {
  const b = fields(body);
  const spec = specOf(b.id);
  const why = needReason(b.reason);
  const err = checkPrompt(spec, b.body);
  if (err) throw new PromptError(400, err);
  const text = b.body as string;
  await locked(async () => {
    const { good, raw } = await activeOf(store);
    if ((good.get(spec.id)?.body ?? spec.def) === text && !brokenOf(good, raw, spec.id)) throw new PromptError(400, "ничего не меняется — текст тот же");
    const v = await store.addPromptVersion(spec.id, text, now.toISOString(), by, why).catch((e: unknown) => {
      // Другая копия сервера записала версию с тем же номером одновременно (UNIQUE (prompt_id, version)).
      if (isUniqueClash(e)) throw new PromptError(409, "промпт только что изменили — обновите страницу");
      throw e;
    });
    await store.addAdminLog(by, "prompt_save", `${spec.id} v${raw.get(spec.id)?.version ?? 0}→v${v}`, now, why);
    await loadPrompts(store, now.getTime());
  });
  return promptCard(store, spec.id);
}

/** «Выбрать эту версию» (POST /api/admin/prompts/<id>/select { version, reason }); version 0 — «как в коде». */
export async function selectPrompt(store: Store, by: number, body: unknown, now = new Date()) {
  const b = fields(body);
  const spec = specOf(b.id);
  const why = needReason(b.reason);
  const v = b.version;
  if (typeof v !== "number" || !Number.isSafeInteger(v) || v < 0 || v > MAX_VERSION) throw new PromptError(400, "нужен номер версии");
  await locked(async () => {
    if (v > 0) {
      const row = await store.promptVersion(spec.id, v);
      if (!row) throw new PromptError(404, `нет версии v${v}`);
      const bad = checkPrompt(spec, row.body);
      if (bad) throw new PromptError(400, `версия v${v} не подходит к нынешнему коду: ${bad}`);
    }
    // «Было» — номер из prompt_active как есть: записанную негодную версию можно сменить на «как в коде».
    const cur = (await activeOf(store)).raw.get(spec.id)?.version ?? 0;
    if (cur === v) throw new PromptError(400, "эта версия уже действует");
    await store.setPromptActive(spec.id, v, now.toISOString(), by);
    await store.addAdminLog(by, "prompt_select", `${spec.id} v${cur}→v${v}`, now, why);
    await loadPrompts(store, now.getTime());
  });
  return promptCard(store, spec.id);
}

/** Нарушение UNIQUE: sqlite — текст ошибки, Postgres — код 23505. */
function isUniqueClash(e: unknown): boolean {
  const x = e as { code?: unknown; message?: unknown } | null;
  return x?.code === "23505" || /UNIQUE constraint|duplicate key/i.test(String(x?.message ?? ""));
}
/** Записанная действующая версия (номер > 0), которая не подходит к нынешнему коду: модель получает «как в коде». */
const brokenOf = (good: Map<string, unknown>, raw: Map<string, PromptActiveRow>, id: string) => (raw.get(id)?.version ?? 0) > 0 && !good.has(id);

